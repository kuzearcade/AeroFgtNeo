; ================================================================ timer IRQ
hal_timer:
	ifne DIAGLAB
	bra     lab_irq
	endif
	ifeq DIRECT-1
	tst.b   HAL_MODE                ; (hal/sched.s: the game's vblank; boot detection)
	beq.w   sch_timer
	bra.w   hal_timer_hal
	endif
	tst.b   HAL_MODE
	bne.w   hal_timer_hal
	; ---- virtual vblank taken: fixed-length path into the sled (C_S cycles)
	move.l  sp,HAL_SAVED_SP
	lea     HAL_STACK_TOP,sp
	movem.l d0-d7/a0-a6,-(sp)
	move.w  #ACK_TIMER,REG_IRQACK
	move.b  HAL_MPROBE,HAL_MODE             ; MODE_PROBE or MODE_PROBE_M
	move.w  HAL_RW_HI,REG_TIMERHIGH         ; reload after the probe: wake W
	move.w  HAL_RW_LO,REG_TIMERLOW
	move.w  #$2100,sr                       ; let the probe in
hal_sled:
	rept SLED_NOPS
	nop
	endr
	bra.w   hal_fault1                      ; probe never arrived

hal_timer_hal:
	cmpi.b  #MODE_PROBE2,HAL_MODE
	beq.w   hal_probe2
	cmpi.b  #MODE_WAKE,HAL_MODE
	beq.w   hal_wake
	cmpi.b  #MODE_PROBE,HAL_MODE
	beq.w   hal_probe
	cmpi.b  #MODE_SYNC,HAL_MODE
	beq.w   hal_sync
	cmpi.b  #MODE_PROBE1B,HAL_MODE
	beq.w   hal_probe_b
	cmpi.b  #MODE_PROBE2B,HAL_MODE
	beq.w   hal_probe2b
	cmpi.b  #MODE_WAKE_M,HAL_MODE
	beq.w   hal_wake_m
	cmpi.b  #MODE_PROBE_M,HAL_MODE
	beq.w   hal_probe_m
	cmpi.b  #MODE_PROBE2_M,HAL_MODE
	beq.w   hal_probe2_m
	cmpi.b  #MODE_SYNC_M,HAL_MODE
	beq.w   hal_sync_m
	cmpi.b  #MODE_DETECT,HAL_MODE
	beq.w   hal_det_irq
	bra.w   hal_fault2                      ; timer IRQ in an unexpected mode

; ---------------------------------------------------------------- wake
; The STOP wake latency is not exactly predictable (STOP idle phase + E clock),
; so the wake only re-enters the sled on a fixed path; a second chain-anchored
; probe then pins tau_w down exactly.
hal_wake:
	move.w  #ACK_TIMER,REG_IRQACK
	move.b  #MODE_PROBE2,HAL_MODE
	move.w  #$2100,sr
	bra.w   hal_sled
hal_wake_m:
	move.w  #ACK_TIMER,REG_IRQACK
	move.b  #MODE_PROBE2_M,HAL_MODE
	move.w  #(Q2B/2-1)>>16,REG_TIMERHIGH    ; reload at probe 2: probe 2b
	move.w  #(Q2B/2-1)&$ffff,REG_TIMERLOW
	move.w  #$2100,sr
	bra.w   hal_sled

; ---------------------------------------------------------------- probe 2
; Constant-time path: the stacked PC indexes a table precomputed by hal_probe
; (one entry per possible sled position).  Each entry holds the relative timer
; load that places the next virtual vblank exactly, written at a fixed cycle
; after this vector start, and the true residue of that vblank.
hal_probe2_m:
	move.w  #ACK_TIMER,REG_IRQACK           ; 20
	move.w  #$00ff,REG_TIMERHIGH            ; 20  reload at probe 2b: far away (its
	move.w  #$ffff,REG_TIMERLOW             ; 20  handler loads T_next only C_LB in)
	move.l  2(sp),HAL_P2PC                  ; 32
	addq.l  #6,sp                           ; 8   (probe 2b's frame goes here)
	move.b  #MODE_PROBE2B,HAL_MODE          ; 20
	move.w  #$2100,sr                       ; 16
hal_sled2b:
	rept SLED2B_NOPS
	nop
	endr
	bra.w   hal_fault1
; probe 2b: fixed path to the counter load and to the original handler
hal_probe2b:
	move.w  #ACK_TIMER,REG_IRQACK
	move.w  HAL_TRES,HAL_RBASE
	lea     HAL_TLOAD,a0
	moveq   #0,d0
	move.w  #AUTOANIM_OFF|TIMER_IRQ_EN|TIMER_REPEAT|TIMER_LOAD_REL,REG_LSPCMODE
	move.w  0(a0,d0.l),REG_TIMERHIGH
hal_p2b_load:
	move.w  2(a0,d0.l),REG_TIMERLOW         ; counter load (C_LB after the vector start)
	move.w  #AUTOANIM_OFF|TIMER_IRQ_EN|TIMER_REPEAT,REG_LSPCMODE
	move.w  #(Q1/2-1)>>16,REG_TIMERHIGH     ; reload at T_k+1: the next probe
	move.w  #(Q1/2-1)&$ffff,REG_TIMERLOW
	move.b  #MODE_GAME,HAL_MODE
	lea     HAL_STACK_TOP-15*4,sp
	movem.l (sp)+,d0-d7/a0-a6
	move.l  HAL_SAVED_SP,sp
	move.w  HAL_CCR,ccr
hal_p2b_jmp:
	jmp     ORIG_IRQ                        ; C2PB after the vector start

hal_probe2:
	move.w  #ACK_TIMER,REG_IRQACK
	move.l  2(sp),d0
	sub.l   #hal_sled+2*JMIN,d0
	cmp.l   #2*NTAB,d0
	bhs.w   hal_p2late                      ; outside the table: the wake came late
hal_probe2_idx:
	lsl.l   #2,d0                           ; 8 bytes per entry
	lea     HAL_JTAB,a0
	tst.w   4(a0,d0.l)
	ifne DIAGBUILD
	beq.w   hal_fault3d
	else
	beq.w   hal_fault3                      ; impossible position (no residue match)
	endif
	move.w  6(a0,d0.l),HAL_RBASE
	move.w  #AUTOANIM_OFF|TIMER_IRQ_EN|TIMER_REPEAT|TIMER_LOAD_REL,REG_LSPCMODE
	move.w  0(a0,d0.l),REG_TIMERHIGH
	move.w  2(a0,d0.l),REG_TIMERLOW         ; counter load (C_L cycles after vector start)
	move.w  #AUTOANIM_OFF|TIMER_IRQ_EN|TIMER_REPEAT,REG_LSPCMODE
	move.w  #(Q1/2-1)>>16,REG_TIMERHIGH     ; reload at T_k+1: the next probe
	move.w  #(Q1/2-1)&$ffff,REG_TIMERLOW
	move.b  #MODE_GAME,HAL_MODE
	lea     HAL_STACK_TOP-15*4,sp
	movem.l (sp)+,d0-d7/a0-a6
	move.l  HAL_SAVED_SP,sp
	move.w  HAL_CCR,ccr
	rept WAKE_PAD4
	nop
	endr
	rept WAKE_PAD6
	exg     d0,d0
	endr
	jmp     ORIG_IRQ                        ; C2P cycles after the vector start

; The slot ran past its wake expiry W: the wake was taken at the STOP and probe 2
; came Q2 multiples later than planned, outside the table.  Every valid table entry
; holds the same counter load and residue (only validity depends on the class), and
; Q2 = 0 mod 10 keeps the residues, so any valid entry resumes exactly - provided the
; rest of the path runs a multiple of 10 cycles later: 10 (bhs taken) - 12 (not
; taken) + 20 + 28 + 20 + 20 + 4 + 10 = 100.  The HAL no longer knows T's phase:
; the idle loop runs the replica (hal/idle.s) and the probe recalibrates it.
hal_p2late:
	move.l  HAL_JFALL,d0                    ; 20: JCLASS entry of a valid class (/4)
	addq.l  #1,HAL_LATEWAKE                 ; 28
	st      HAL_TPH_DIRTY                   ; 20
	move.w  #TR_REPLICA,G_TRAMP             ; 20
	nop                                     ; 4
	bra.w   hal_probe2_idx                  ; 10

; ---------------------------------------------------------------- probe
; Stacked PC (in the sled) -> exact entry time X; then precompute probe-2 table,
; plan the next frame and do the HAL work.  Times are relative to the chain
; expiry the probe is anchored to (BASE), whose true cycle count mod 10 is HAL_RBASE.
hal_probe_m:
	; MiSTer probe 1: its sled position, then probe 1b (the reload after probe 1 is Q1B)
	move.w  #ACK_TIMER,REG_IRQACK           ; 20
	move.w  REG_LSPCMODE,HAL_LINE_AT_PROBE  ; 28  raster position, for phase lock
	move.w  HAL_RWB_HI,REG_TIMERHIGH        ; 28  reload after probe 1b: wake W
	move.w  HAL_RWB_LO,REG_TIMERLOW         ; 28
	move.l  2(sp),HAL_P1PC                  ; 32
	addq.l  #6,sp                           ; 8
	move.b  #MODE_PROBE1B,HAL_MODE          ; 20
	move.w  #$2100,sr                       ; 16
hal_sled1b:
	rept SLED1B_NOPS
	nop
	endr
	bra.w   hal_fault1
hal_probe_b:
	move.l  HAL_STACK_TOP+P2PC_OFF,HAL_P2BPC        ; 36 (before any call overwrites it)
	move.w  #ACK_TIMER,REG_IRQACK
	move.w  #(Q2/2-1)>>16,REG_TIMERHIGH     ; reload at W: probe 2 at W + Q2
	move.w  #(Q2/2-1)&$ffff,REG_TIMERLOW
	move.b  #MODE_PROBE_M,HAL_MODE
	cmpi.w  #$ff00,HAL_CAL                  ; (as hal_probe)
	beq.s   .trk
	bsr     hal_cal_vernier                 ; PREFIX_PB cycles after the vector start
	st      HAL_CALNOW
	bra.s   .meas
.trk:	move.l  HAL_STACK_TOP+P2PC_OFF,d0
	sub.l   #hal_sled+2*JMIN,d0
	bsr     hal_tph_next
.meas:	; probe 1 boundary = BASE + PROBE_AT + 6 + r (r = 0, 2: entries are even after
	; BASE), probe 1b's at sled-1b position m+1 if r = 0, m if r = 2
	move.l  HAL_P1PC,d0
	sub.l   #hal_sled,d0
	add.l   d0,d0                           ; 4 j1
	move.l  2(sp),d2
	sub.l   #hal_sled1b,d2
	add.l   d2,d2                           ; 4 j1b
	moveq   #0,d3
	cmpi.l  #Q1B-LAT_M-H1+2,d2
	beq.s   .r0
	moveq   #2,d3
	cmpi.l  #Q1B-LAT_M-H1-2,d2
	bne.w   hal_fault4                      ; neither: the model is wrong
.r0:	move.l  HAL_PROBE_AT,d1
	sub.l   d0,d1
	add.l   d3,d1
	addq.l  #6,d1                           ; sled start - BASE
	move.l  d1,d4
	add.l   d0,d4
	add.l   d2,d4
	addi.l  #2*LAT_M+H1,d4
	move.l  d4,HAL_P1BVS                    ; probe-1b vector start - BASE
	subi.l  #C_S,d1                         ; X - BASE, the Neo's (IRQ at LAT_M)
	move.l  d1,HAL_DX_MEAS
	subi.l  #LAT_M,d1                       ; the boundary: the original's vector
	move.w  HAL_RBASE,d2                    ; starts LAT[its E phase] after it
	add.w   d1,d2
	addi.w  #1000,d2
	ext.l   d2
	divu    #10,d2
	swap    d2
	lea     hal_lat_table,a1
	moveq   #0,d3
	move.b  (a1,d2.w),d3
	beq.w   hal_fault6                      ; boundary not on the IACK parity
	add.l   d3,d1
	move.l  d1,HAL_DX                       ; dX = X - BASE (the original's)
	bra.s   hal_probe_fix

; MAME timing model
hal_probe:
	move.w  #ACK_TIMER,REG_IRQACK
	move.w  REG_LSPCMODE,HAL_LINE_AT_PROBE  ; raster position, for phase lock
	move.w  #(Q2/2-1)>>16,REG_TIMERHIGH     ; reload at W: probe 2 at W + Q2
	move.w  #(Q2/2-1)&$ffff,REG_TIMERLOW
	; T's raster phase (hal/idle.s): calibrate once, then track it through the
	; probe-2 class of the last frame
	cmpi.w  #$ff00,HAL_CAL                  ; HAL_CAL set, HAL_TPH_DIRTY clear?
	beq.s   .trk
	bsr     hal_cal_vernier                 ; PREFIX_P cycles after the vector start
	st      HAL_CALNOW
	bra.s   .meas
.trk:	move.l  HAL_STACK_TOP+P2PC_OFF,d0
	sub.l   #hal_sled+2*JMIN,d0
	bsr     hal_tph_next
.meas:	move.l  2(sp),d0                        ; stacked PC
	sub.l   #hal_sled,d0
	lsr.l   #1,d0                           ; j
	move.l  HAL_PROBE_AT,d1
	lsl.l   #2,d0
	sub.l   d0,d1
	add.l   #K0-C_S-2,d1                    ; X candidates: d1 .. d1+3
	bsr     hal_snap5
	bmi.w   hal_fault4
	move.l  d1,HAL_DX                       ; dX = X - BASE
	move.l  d1,HAL_DX_MEAS                  ; (the Neo's own, for the calibration)

hal_probe_fix:
	; interrupted in the patched idle loop (hal/idle.s): the original was at the
	; same boundary (0xbd0 <-> 0xb84) or took it at its next one, 10 cycles later
	; (G_TRAMP <-> after the cmpi, 0xb8c)
	movea.l HAL_SAVED_SP,a0
	move.l  2(a0),d0
	cmpi.l  #$bd0,d0
	bne.s   .fx1
	move.l  #$b84,2(a0)
	bra.s   .fx2
.fx1:	cmpi.l  #G_TRAMP,d0
	bne.s   .fx3
	addi.l  #10,HAL_DX
	bra.s   .fx8c
.fx3:	cmpi.l  #G_TRAMP+TR_CMPI,d0             ; replica (hal/idle.s): same boundaries
	bne.s   .fx4
	move.l  #$b84,2(a0)
	bra.s   .fx2
.fx4:	cmpi.l  #G_TRAMP+TR_HOP,d0
	beq.s   .fx8c
	cmpi.l  #G_TRAMP+TR_BCS,d0
	bne.s   .fx2
.fx8c:	move.l  #$b8c,2(a0)
.fx2:
	tst.b   HAL_CALNOW
	beq.s   .cald
	sf      HAL_CALNOW
	move.l  2(sp),d0                        ; this probe's sled position j
	sub.l   #hal_sled,d0
	lsr.l   #1,d0
	bsr     hal_cal_finish
.cald:	; T's line for the phase lock: the probe read the raster ~Q1+60 cycles after T
	move.w  HAL_LINE_AT_PROBE,d0
	bsr     hal_vpos_of
	subi.w  #(Q1+60)/768,d0
	bpl.s   .tl
	addi.w  #264,d0
.tl:	move.w  d0,HAL_TLINE

; ---------------------------------------------------------------- frame
; Common to the probe and the idle entry: HAL_DX = X - T known.
hal_frame:
	ifne DIAG_FAULTAT
	cmpi.l  #DIAG_FAULTAT,HAL_FRAMES        ; (diagnostic test: show the dump)
	beq.w   hal_fault5
	endif
	; y_next - e (relative), e = virtual start of the original handler
	tst.b   HAL_BOOT
	beq.s   .reg
	move.l  #BOOT_YNEXT_MINUS_E,d6
	clr.b   HAL_BOOT
	bra.s   .tn
.reg:	bsr     hal_next_y                      ; d2 = y_next - y_cur
	move.l  d2,d6
	sub.l   HAL_DX,d6
	; returning to the idle loop's bcs with C set costs POST_DELAY cycles (hal/idle.s)
	movea.l HAL_SAVED_SP,a0
	cmpi.l  #$b8c,2(a0)
	bne.s   .tn
	btst    #0,1(a0)
	beq.s   .tn
	addi.l  #POST_DELAY,d6
.tn:
	; ---- probe-2 table.  With A = DW + Q2+K0-2 and R0 = (A + RBASE) mod 10, class i
	; (j2 = JMIN + i) snaps tau_w by c = (5 - R0 + C_S2 + 4 j2) mod 10 (valid if
	; c <= 3; same rule as hal_snap5), probe 2 is then taken at b2 = A + c plus the
	; latency for (R0 + c) mod 10, and the counter load value is the same for every
	; class.  Two divides per frame instead of ~30.
	tst.b   HAL_MISTER
	beq.w   .mtab
	; MiSTer: last frame's probe 2 / 2b where the model has them?  Else T's phase is lost
	; (a late wake): recalibrate at the next probe
	move.l  HAL_P2BPC,d0
	sub.l   #hal_sled2b+2*M2,d0
	cmpi.l  #2,d0
	bhi.s   .lost                           ; (unsigned: m2 or m2+1 only)
	move.l  HAL_P2PC,d0
	sub.l   #hal_sled+2*(J2M-1),d0
	cmpi.l  #6,d0
	bls.s   .p2ok                           ; J2M-1 .. J2M+2
.lost:	st      HAL_TPH_DIRTY
.p2ok:
	; probe 2b loads T_next C_LB after its vector start and resumes C2PB after it:
	; one counter load (shortened by RELOFS); T_next's residue is y_next mod 10;
	; T_next - T for the tracking: probe 2's boundary W+Q2+6 (probe 2b at m2+1) or
	; W+Q2+8 (at m2), probe 2b's vector start from there, C2PB, d6
	move.l  d6,d2
	add.l   #C2PB-C_LB-W_IN-RELOFS,d2
	lsr.l   #1,d2
	subq.l  #1,d2                           ; counter load (hi:lo)
	move.l  d2,HAL_TLOAD
	move.l  HAL_YLAST,d0                    ; y of T_next = YLAST - DYNEXT
	sub.l   HAL_DYNEXT,d0
	move.l  d0,d1
	clr.w   d1
	swap    d1                              ; high word a: x mod 10 = (6a + b) mod 10
	mulu    #6,d1
	andi.l  #$ffff,d0
	add.l   d1,d0
	divu    #10,d0
	swap    d0                              ; residue of T_next
	move.w  d0,HAL_TRES
	move.l  HAL_DW,d5
	add.l   #Q2+6+LAT_M+H2+4*(M2+1)+LAT_M+C2PB,d5   ; T_next - T - d6 (probe 2b at m2+1)
	move.l  d5,HAL_DRES
	add.l   d6,d5
	move.l  d5,HAL_DTNEXT
	lea     HAL_DTN_CLASS,a5                ; tracking: the class of probe 2b's position
	moveq   #5-1,d1
.jm:	move.l  d5,(a5)+
	dbra    d1,.jm
	lea     HAL_DTN_CLASS,a5
	subq.l  #2,d5                           ; (at m2: 2 cycles less)
	move.l  d5,4*P2B_CLS_M(a5)
	bra.w   .jdone
.mtab:
	move.l  HAL_DW,d5
	add.l   #Q2+K0-2,d5                     ; A
	moveq   #0,d0
	move.w  HAL_RBASE,d0
	move.l  d5,d3
	add.l   d0,d3
	add.l   #100000,d3
	divu    #10,d3
	swap    d3
	andi.l  #$ffff,d3                       ; R0
	move.l  d6,d4
	add.l   #C2P+100000,d4
	divu    #10,d4
	swap    d4
	add.w   d3,d4                           ; R0 + S, S = (C2P + d6) mod 10
	movea.w d4,a4
	move.l  d6,d2
	add.l   #C2P-C_L-W_IN,d2
	lsr.l   #1,d2
	subq.l  #1,d2                           ; counter load (hi:lo)
	lea     HAL_JCLASS,a1
	lea     HAL_DTN_CLASS,a5
	lea     hal_mod10,a3
	lea     hal_cltab,a2            ; c + latency of each class for this R0
	move.w  d3,d0
	lsl.w   #2,d0
	add.w   d3,d0
	adda.w  d0,a2
	move.l  d5,d4
	add.l   #C2P,d4                 ; T_next - T = d4 + c + latency + d6
	moveq   #5-1,d1
.jt:	moveq   #0,d0
	move.b  (a2)+,d0
	bmi.s   .bad                    ; (the class cannot occur)
	move.l  d2,(a1)
	move.w  #1,4(a1)
	move.w  a4,d7
	add.w   d0,d7
	move.b  (a3,d7.w),d7            ; residue of T_next
	ext.w   d7
	move.w  d7,6(a1)
	add.l   d4,d0
	move.l  d0,HAL_DRES
	add.l   d6,d0
	move.l  d0,HAL_DTNEXT
	move.l  d0,(a5)                 ; T_next - T of this class (tracking)
	bra.s   .nx
.bad:	clr.w   4(a1)
.nx:	addq.l  #8,a1
	addq.l  #4,a5
	dbra    d1,.jt
	; a valid class for late wakes (hal_p2late)
.jdone:	lea     HAL_JCLASS+4,a1
	moveq   #(HAL_JCLASS-HAL_JTAB)/4,d0
.fv:	tst.w   (a1)
	bne.s   .fvd
	addq.l  #8,a1
	addq.l  #2,d0
	cmpi.l  #(HAL_JCLASS-HAL_JTAB)/4+10,d0
	blo.s   .fv
.fvd:	move.l  d0,HAL_JFALL
	subi.l  #(HAL_JCLASS-HAL_JTAB)/4,d0     ; 2 * class
	addi.l  #hal_sled+2*JMIN,d0
	move.l  d0,HAL_JFALL_PC                 ; its sled position (class + 0 * 5)
	; fill the table: entry i takes class (i mod 5), so JTAB is JCLASS repeated
	movem.l HAL_JCLASS,d0-d7/a0/a2
	lea     HAL_JTAB,a1
	rept (NTAB+4)/5
	movem.l d0-d7/a0/a2,(a1)
	lea     40(a1),a1
	endr
	bsr     hal_phase_lock
	; plan the next wake so the T period stays ~ one Neo frame:
	; T'' - T' = dy' - dX' + Q1 + R_w' + WAKE_EXTRA
	move.l  #FRAME_CYCLES-Q1-WAKE_EXTRA,d3
	add.l   HAL_DX,d3
	sub.l   HAL_DYNEXT,d3
	add.l   HAL_PHASE_ADJ,d3
	clr.l   HAL_PHASE_ADJ
	andi.l  #$fffffffe,d3                   ; chain expiries stay on one parity
	move.l  d3,d4
	add.l   #Q1,d4
	move.l  d4,HAL_DW_NEXT
	tst.b   HAL_MISTER
	beq.s   .rw
	move.l  d3,d4                           ; MiSTer: probe 1b -> W
	sub.l   #Q1B,d4
	lsr.l   #1,d4
	subq.l  #1,d4
	move.w  d4,HAL_RWB_LO
	swap    d4
	move.w  d4,HAL_RWB_HI
	move.l  #Q1B,d3                         ; probe 1 -> probe 1b
.rw:	lsr.l   #1,d3
	subq.l  #1,d3
	move.w  d3,HAL_RW_LO
	swap    d3
	move.w  d3,HAL_RW_HI

	; ---- HAL work for this frame (outside virtual time)
	move.l  HAL_SAVED_SP,a0
	move.w  (a0),HAL_CCR                    ; interrupted SR: CCR for the handler
	move.b  d0,REG_WATCHDOG
	addq.l  #1,HAL_FRAMES
	bsr     hal_log
	bsr     hal_tramp
	bsr     hal_deadline
	ifeq ASSIST
	cmpi.l  #1,HAL_FRAMES
	beq.s   .wvb                            ; boot frame: calibration instead (black screen)
	bsr     hal_vid_prep
	endif
	; inputs are latched by the hardware/MAME at the start of the real vblank,
	; so copy them once the beam is inside it (vpos 242..263: the line counter
	; turns 241 just before MAME's frame update); meanwhile do the work that
	; must not touch the display.  (Unlocked, e.g. at boot, the deadline may
	; come first.)
.wvb:	move.w  REG_LSPCMODE,d0
	lsr.w   #7,d0
	cmpi.w  #$100+242,d0
	bhs.s   .inp                            ; in vblank (242..255)
	cmpi.w  #$100,d0
	blo.s   .inp                            ; in vblank (256..263)
	moveq   #COMMIT_LINES,d0
	bsr     hal_late_n                      ; keep the commit's share of the budget
	bne.s   .inp
	ifeq ASSIST
	bsr     hal_vid_early
	endif
	bra.s   .wvb
.inp:
	ifne HAL_DIAG
	bsr     hal_vpos
	move.w  d0,HAL_DBG_INP
	endif
	bsr     hal_inputs
	ifne ASSIST
	; MAME-only assist board: draw this frame.  Kept after the real vblank so the
	; board presents it one Neo frame later, after the handler's palette writes.
	move.w  d0,ASSIST_SNAPSHOT
	endif
	ifeq ASSIST
	cmpi.l  #1,HAL_FRAMES
	beq.s   .vc
	bsr     hal_vid_commit
.vc:
	endif

	; the wake must find the CPU in STOP: if the slot ran (nearly) into W, T's phase
	; will not be what the HAL thinks (hal_p2late): run the replica, recalibrate
	moveq   #1-MARGIN_LINES,d0                ; within a line of W itself
	bsr     hal_late_raw
	beq.s   .ontime
	st      HAL_TPH_DIRTY
	move.w  #TR_REPLICA,G_TRAMP
	addq.l  #1,HAL_OVERRUN
	ifne OVR_DIAG
	move.w  #1,OVD_SITE
	bsr     ovd_note
	endif
	move.l  HAL_DBG_LASTPC,HAL_DBG_OVRPC    ; diagnostics: the check that let it run on
	move.w  HAL_DBG_LASTOK,HAL_DBG_OVRLN
.ontime:
	move.l  HAL_DW_NEXT,d0
	move.l  d0,HAL_DW
	sub.l   HAL_RELOFS,d0
	move.l  d0,HAL_DWR
	move.l  #Q1,HAL_PROBE_AT

	move.b  HAL_MWAKE,HAL_MODE              ; MODE_WAKE or MODE_WAKE_M
	stop    #$2100                          ; wake expiry -> hal_wake

	ifne OVR_DIAG
; diagnostics: copy the last passing check, how far past the deadline, the stage
ovd_note:
	move.l  d0,-(sp)
	move.l  OVD_PC,OVD_OPC
	move.w  OVD_LN,OVD_OLN
	move.w  HAL_EARLY_ST,OVD_EST
	bsr.s   ovd_ln
	move.w  d0,OVD_OAT
	move.l  a0,-(sp)
	lea     OVD_T,a0
	moveq   #9-1,d0
.c:	move.w  (a0),18(a0)
	move.w  #$7fff,(a0)+            ; (steps not reached this commit: $7fff)
	dbra    d0,.c
	movea.l (sp)+,a0
	move.l  (sp)+,d0
	rts
; d0 = lines past HAL_KDL now (as hal_late_raw counts)
ovd_ln:
	move.w  REG_LSPCMODE,d0
	lsr.w   #7,d0
	cmp.w   HAL_K0R,d0
	bhs.s   .p
	addi.w  #264,d0
.p:	sub.w   HAL_KDL,d0
	rts
	endif

; d1 = first of four candidate times (relative to BASE); returns the one whose true
; cycle count is 5 mod 10 (an IACK-aligned vector start) in d1, N clear; N set if none.
hal_snap5:
	movem.l d2-d3,-(sp)
	moveq   #3,d2
.s:	move.l  d1,d3
	add.w   HAL_RBASE,d3
	add.l   #100000,d3                      ; keep it positive; quotient must fit 16 bits
	divu    #10,d3
	swap    d3
	cmpi.w  #5,d3
	beq.s   .ok
	addq.l  #1,d1
	dbra    d2,.s
	movem.l (sp)+,d2-d3
	move.w  #$08,ccr                        ; N: no candidate matched
	rts
.ok:	movem.l (sp)+,d2-d3
	move.w  #$00,ccr
	rts

; IRQ latency in the running CPU (NOP sled): boundary cycle mod 10 -> vector start
; (measured in MAME: E clock synchronisation of the autovector acknowledge)
hal_lat_table:
	dc.b    0,LAT1,0,LAT3,0,LAT5,0,LAT7,0,LAT9
	even

; x mod 10 for x = 0..99
hal_mod10:
jci	set 0
	rept 100
	dc.b    jci-(jci/10)*10
jci	set jci+1
	endr
	even
JC_K	equ (5+C_S2+4*JMIN)-((5+C_S2+4*JMIN)/10)*10

; probe-2 class i (0..4) for R0 (0..9), 5 bytes per R0: tau_w snaps by c = (JC_K + 10 -
; R0 + 4i) mod 10 (valid if c <= 3), then the latency for (R0 + c) mod 10; c + latency,
; or $ff when the class cannot occur
hal_cltab:
clr_	set 0
	rept 10
cli_	set 0
	rept 5
clx_	set JC_K+10-clr_+4*cli_
clc_	set clx_-(clx_/10)*10
clm_	set (clr_+clc_)-((clr_+clc_)/10)*10
cll_	set 0
	ifeq clm_-1
cll_	set LAT1
	endif
	ifeq clm_-3
cll_	set LAT3
	endif
	ifeq clm_-5
cll_	set LAT5
	endif
	ifeq clm_-7
cll_	set LAT7
	endif
	ifeq clm_-9
cll_	set LAT9
	endif
	ifle clc_-3
	ifne cll_
	dc.b    clc_+cll_
	else
	dc.b    $ff
	endif
	else
	dc.b    $ff
	endif
cli_	set cli_+1
	endr
clr_	set clr_+1
	endr
	even

; ---------------------------------------------------------------- phase lock
; Steer T_k (virtual vblank) to real scanline PHASE_LINE (HAL_TLINE = T's vpos) so
; the HAL slot always contains the real vblank.
hal_phase_lock:
	move.w  HAL_TLINE,d3
	subi.w  #PHASE_LINE,d3                  ; error in lines
	cmpi.w  #132,d3
	blt.s   .v1
	subi.w  #264,d3
.v1:	cmpi.w  #-132,d3
	bgt.s   .v2
	addi.w  #264,d3
.v2:	muls    #-384,d3                        ; correct half a line per line of error
	cmpi.l  #4000,d3
	ble.s   .v3
	move.l  #4000,d3
.v3:	cmpi.l  #-4000,d3
	bge.s   .v4
	move.l  #-4000,d3
.v4:	move.l  d3,HAL_PHASE_ADJ
	rts

; diagnostics ring for the calibration harness: dX, dRES, dTnext per frame
hal_log:
	move.l  HAL_FRAMES,d0
	andi.w  #31,d0
	lsl.w   #2,d0
	move.w  d0,d1
	add.w   d0,d0
	add.w   d1,d0                   ; x 12
	lea     HAL_LOG,a0
	adda.w  d0,a0
	move.l  HAL_DX,(a0)+
	move.l  HAL_DRES,(a0)+
	move.l  HAL_DTNEXT,(a0)+
	rts

; ---------------------------------------------------------------- y_k
; Advance x = k*P (integer + remainder in 250 as units) and return
; d2 = y_{k+1} - y_k (precomputed in HAL_DYNEXT); y = first odd cycle >= floor(x), minus 2 (see hal_next_y).
hal_next_y:
	move.l  HAL_DYNEXT,d2
	movem.l d3-d5,-(sp)
	move.l  HAL_XI,d3
	move.l  HAL_XR,d4
	add.l   #P_FRAC,d4
	add.l   #P_INT,d3
	cmp.l   #P_MOD,d4
	blo.s   .nc
	sub.l   #P_MOD,d4
	addq.l  #1,d3
.nc:	move.l  d3,HAL_XI
	move.l  d4,HAL_XR
	; Fitted against MAME traces of both machines: the original takes the IRQ at
	; the first sampling point >= floor(x); the LSPC timer must be scheduled at the
	; first odd (post-IACK parity) cycle >= floor(x), minus 2, to land identically.
	move.l  d3,d5
	btst    #0,d5
	bne.s   .y
	addq.l  #1,d5
.y:	subq.l  #2,d5
	move.l  d5,d4
	sub.l   HAL_YLAST,d4
	move.l  d5,HAL_YLAST
	move.l  d4,HAL_DYNEXT
	movem.l (sp)+,d3-d5
	rts

; ================================================================ takeover
hal_user:
	move.b  BIOS_USER_REQUEST,d0
	bne.s   .take
	jmp     SYSTEM_RETURN
.take:
	move.w  #$2700,sr
	move.b  d0,REG_WATCHDOG
	move.b  d0,REG_SWPROM           ; cartridge vector table
	move.b  d0,REG_CRTFIX           ; cartridge fix tiles (all transparent)
	move.b  d0,REG_SRAMUNLOCK       ; backup RAM holds the original video RAM
	move.b  d0,REG_PALBANK0
	move.b  d0,REG_NOSHADOW

	; soft DIPs: copy the BIOS settings before the original program reuses its RAM
	lea     BIOS_GAME_DIP,a0
	lea     HAL_SOFTDIP,a1
	moveq   #15,d1
.dip:	move.b  (a0)+,(a1)+
	dbra    d1,.dip

	; the original board powers up with all RAM cleared (as MAME does); backup RAM
	; keeps the previous session and work RAM holds BIOS state, so clear both
	; (everything the original or the HAL uses, except the soft DIP copy)
	moveq   #0,d0
	lea     $100000,a0
	move.w  #$10000/16-1,d1
.wr:	move.l  d0,(a0)+
	move.l  d0,(a0)+
	move.l  d0,(a0)+
	move.l  d0,(a0)+
	move.b  d0,REG_WATCHDOG
	dbra    d1,.wr
	lea     $d00420,a0
	move.w  #(HAL_SOFTDIP-$d00420)/4-1,d1
.br1:	move.l  d0,(a0)+
	dbra    d1,.br1
	lea     HAL_SOFTDIP+16,a0
	move.w  #($d10000-HAL_SOFTDIP-16)/16-1,d1
.br2:	move.l  d0,(a0)+
	move.l  d0,(a0)+
	move.l  d0,(a0)+
	move.l  d0,(a0)+
	move.b  d0,REG_WATCHDOG
	dbra    d1,.br2

	move.w  #AUTOANIM_OFF,REG_LSPCMODE
	move.w  #ACK_IRQ3|ACK_TIMER|ACK_VBLANK,REG_IRQACK
	lea     HAL_STACK_TOP,sp
	ifeq DIAGLAB
	bsr     hal_detect                      ; (first: the rest of the boot keeps its timing)
	endif
	bsr     hal_video_init
	ifeq ASSIST
	bsr     hal_vid_init
	endif
	bsr     hal_io_init
	ifne DIAGLAB
	bsr     hal_timing_init
	bsr     hal_sound_start
	bra     lab_main
	endif
	bsr     hal_timing_init
	bsr     hal_sound_start
	ifeq DIRECT-1
	bra     sch_boot                ; (hal/sched.s: no virtual-time start)
	endif

	; start from a fixed raster line, whatever the BIOS and hal_detect took: the
	; early frames (before the phase lock settles) then see the real vblanks in
	; the same places every boot
.sl1:	move.w  REG_LSPCMODE,d0
	lsr.w   #7,d0
	cmpi.w  #BOOT_SYNC_LINE,d0
	beq.s   .sl1
.sl2:	move.w  REG_LSPCMODE,d0
	lsr.w   #7,d0
	cmpi.w  #BOOT_SYNC_LINE,d0
	bne.s   .sl2
	; synchronise to the LSPC timer: one short relative expiry, then STOP
	move.b  #MODE_SYNC,HAL_MODE
	tst.b   HAL_MISTER
	beq.s   .sy
	move.b  #MODE_SYNC_M,HAL_MODE
.sy:
	move.w  #AUTOANIM_OFF|TIMER_IRQ_EN|TIMER_REPEAT|TIMER_LOAD_REL,REG_LSPCMODE
	move.w  #0,REG_TIMERHIGH
	move.w  #200,REG_TIMERLOW
	move.w  #AUTOANIM_OFF|TIMER_IRQ_EN|TIMER_REPEAT,REG_LSPCMODE
	move.w  #$00ff,REG_TIMERHIGH             ; next reload far away
	move.w  #$ffff,REG_TIMERLOW
	stop    #$2100

; Sync wake: vector start tau_s has true cycle = 5 mod 10.  Fixed path from here
; to the original reset code; the boot chain expiry BASE is placed relative to it.
hal_sync:
	move.w  #ACK_TIMER,REG_IRQACK
	move.w  #AUTOANIM_OFF|TIMER_IRQ_EN|TIMER_REPEAT|TIMER_LOAD_REL,REG_LSPCMODE
	move.w  #(SYNC_TO_BASE/2-1)>>16,REG_TIMERHIGH
	move.w  #(SYNC_TO_BASE/2-1)&$ffff,REG_TIMERLOW
	move.w  #AUTOANIM_OFF|TIMER_IRQ_EN|TIMER_REPEAT,REG_LSPCMODE
	move.w  #(Q1/2-1)>>16,REG_TIMERHIGH      ; after BASE: an expiry every Q1 while masked
	move.w  #(Q1/2-1)&$ffff,REG_TIMERLOW
	move.b  #MODE_GAME,HAL_MODE
	move.l  #$00d01000,sp                   ; original boot SSP (relocated 0x1b1000)
	moveq   #0,d0
	moveq   #0,d1
	move.w  #$2700,sr
	jmp     ORIG_RESET
; MiSTer: the expiry comes RELOFS later (the extra dispatch delays the load and the
; jump to the reset code alike, so BASE keeps its place in the original's time)
hal_sync_m:
	move.w  #ACK_TIMER,REG_IRQACK
	move.w  #AUTOANIM_OFF|TIMER_IRQ_EN|TIMER_REPEAT|TIMER_LOAD_REL,REG_LSPCMODE
	move.w  #((SYNC_TO_BASE-RELOFS)/2-1)>>16,REG_TIMERHIGH
	move.w  #((SYNC_TO_BASE-RELOFS)/2-1)&$ffff,REG_TIMERLOW
	move.w  #AUTOANIM_OFF|TIMER_IRQ_EN|TIMER_REPEAT,REG_LSPCMODE
	move.w  #(Q1/2-1)>>16,REG_TIMERHIGH      ; after BASE: an expiry every Q1 while masked
	move.w  #(Q1/2-1)&$ffff,REG_TIMERLOW
	move.b  #MODE_GAME,HAL_MODE
	move.l  #$00d01000,sp                   ; original boot SSP (relocated 0x1b1000)
	moveq   #0,d0
	moveq   #0,d1
	move.w  #$2700,sr
	jmp     ORIG_RESET

hal_timing_init:
	clr.w   HAL_RESV
	sf      HAL_BG_EARLY
	sf      HAL_BG_P1
	move.b  #1,HAL_BOOT
	move.w  #BOOT_RBASE,HAL_RBASE
	move.l  #BOOT_PROBE_AT,HAL_PROBE_AT
	move.l  #BOOT_DW,HAL_DW
	move.l  #BOOT_DW,d0
	sub.l   HAL_RELOFS,d0
	move.l  d0,HAL_DWR
	tst.b   HAL_MISTER
	beq.s   .mame
	move.w  #(Q1B/2-1)&$ffff,HAL_RW_LO
	move.w  #(Q1B/2-1)>>16,HAL_RW_HI
	move.w  #((BOOT_DW-BOOT_PROBE_AT-Q1B)/2-1)&$ffff,HAL_RWB_LO
	move.w  #((BOOT_DW-BOOT_PROBE_AT-Q1B)/2-1)>>16,HAL_RWB_HI
	bra.s   .rwd
.mame:	move.w  #((BOOT_DW-BOOT_PROBE_AT)/2-1)&$ffff,HAL_RW_LO
	move.w  #((BOOT_DW-BOOT_PROBE_AT)/2-1)>>16,HAL_RW_HI
.rwd:
	move.l  #X_INIT_INT,HAL_XI
	move.l  #X_INIT_REM,HAL_XR
	move.l  #Y_INIT,HAL_YLAST
	move.l  #DY_INIT,HAL_DYNEXT
	clr.l   HAL_PHASE_ADJ
	clr.l   HAL_FRAMES
	clr.l   HAL_FAULT
	rts

; ================================================================ timing model
; MAME's 68000 takes an autovectored interrupt in step with the E clock, 50..58
; cycles after the instruction boundary; the MiSTer core takes it LAT_M = 44 after
; it.  Two expiries DET_R apart (a reload: exact on both): the first is taken in
; sled 0, its handler enters sled 1 DET_H cycles after its vector start, and the
; second's sled-1 position j gives the first's latency to within 2 (both boundaries
; are the first even one >= expiry + 6): L = DET_R - DET_H - 4j, a multiple of 4,
; is 44 on the MiSTer and 48..60 in MAME.  Four trials, the expiry 2 cycles later
; each time (other E phases).  HAL_FORCE (builder) overrides the result.
DET_H           equ 388+88              ; dispatch (11th mode) + hal_det_irq
DET_R           equ DET_H+LAT_M+80      ; MiSTer: j = 20
DET_TRIALS      equ 4
hal_detect:
	movem.l d0-d7/a0-a2,-(sp)
	lea     HAL_DET_L,a2
	moveq   #0,d6                           ; trials that gave the MiSTer's latency
	moveq   #0,d7
hal_det_trial:
	sf      HAL_DET_N
	move.b  #MODE_DETECT,HAL_MODE
	move.w  #AUTOANIM_OFF,REG_LSPCMODE
	move.w  #ACK_TIMER,REG_IRQACK
	move.w  #AUTOANIM_OFF|TIMER_IRQ_EN|TIMER_REPEAT|TIMER_LOAD_REL,REG_LSPCMODE
	move.w  #0,REG_TIMERHIGH
	move.w  d7,d0
	addi.w  #100,d0
	move.w  d0,REG_TIMERLOW                 ; first expiry ~200 cycles on
	move.w  #AUTOANIM_OFF|TIMER_IRQ_EN|TIMER_REPEAT,REG_LSPCMODE
	move.w  #(DET_R/2-1)>>16,REG_TIMERHIGH  ; then DET_R later
	move.w  #(DET_R/2-1)&$ffff,REG_TIMERLOW
	move.w  #$2100,sr
	rept 160
	nop
	endr
	bra.w   hal_fault1
hal_det_back:                                   ; IPL 7, d0 = 4j
	move.l  #DET_R-DET_H,d1
	sub.l   d0,d1
	move.w  d1,(a2)+
	cmpi.w  #46,d1
	bgt.s   .m
	addq.w  #1,d6
.m:	move.w  #400,d1                         ; the third expiry passes (masked)
.w:	move.b  d0,REG_WATCHDOG
	dbra    d1,.w
	move.w  #AUTOANIM_OFF,REG_LSPCMODE
	move.w  #ACK_TIMER,REG_IRQACK
	addq.w  #1,d7
	cmpi.w  #DET_TRIALS,d7
	blo.w   hal_det_trial
	move.b  d6,HAL_DET_N
	clr.b   HAL_MODE
	ifeq HAL_FORCE
	cmpi.w  #DET_TRIALS-1,d6                ; (a stray trial is outvoted)
	shs     HAL_MISTER
	else
	ifeq HAL_FORCE-2
	st      HAL_MISTER
	else
	sf      HAL_MISTER
	endif
	endif
	move.b  #MODE_PROBE,HAL_MPROBE
	move.b  #MODE_WAKE,HAL_MWAKE
	clr.l   HAL_RELOFS
	tst.b   HAL_MISTER
	beq.s   .x
	move.b  #MODE_PROBE_M,HAL_MPROBE
	move.b  #MODE_WAKE_M,HAL_MWAKE
	move.l  #RELOFS,HAL_RELOFS
.x:	movem.l (sp)+,d0-d7/a0-a2
	rts
; the second expiry: sled-1 position, then back to hal_detect masked
hal_det_2nd:
	move.w  #$00ff,REG_TIMERHIGH            ; the reload after the third: far away
	move.w  #$ffff,REG_TIMERLOW
	move.l  2(sp),d0
	addq.l  #6,sp
	sub.l   #hal_det_sled1,d0
	add.l   d0,d0                           ; 4j
	move.w  #$2700,sr
	bra.w   hal_det_back
hal_det_irq:
	move.w  #ACK_TIMER,REG_IRQACK           ; 20
	tst.b   HAL_DET_N                       ; 16
	bne.s   hal_det_2nd                     ; 8
	st      HAL_DET_N                       ; 20
	addq.l  #6,sp                           ; 8
	move.w  #$2100,sr                       ; 16
hal_det_sled1:
	rept 64
	nop
	endr
	bra.w   hal_fault1

; ================================================================ sound
; Start the original sound driver: the Z80 shim waits for 0x55 0xaa (z80/shim.s).
hal_sound_start:
	ifne DIAGBUILD
	lea     $d00f50,a0                      ; (diagnostics: per byte the wait left and
	endif                                   ; the Z80's reply)
	ifeq DIRECT-1
	moveq   #4-1,d3                         ; (DIRECT: the shim echoes 0x55 before it
.try:	move.b  #$55,d1                         ; leaves its NMI handler - an 0xaa sent at
	bsr.s   .send                           ; once nested in it, was taken for a game
	move.w  #400,d2                         ; command, the driver never started: no
.dly:	move.b  d0,REG_WATCHDOG                 ; sound at all, MAME and MiSTer alike,
	dbra    d2,.dly                         ; 2026-10-17; ~200 us for it to return, and
	move.b  #$aa,d1                         ; again if 0xaa is not echoed)
	bsr.s   .send
	beq.s   .ok
	ifne DIAGBUILD
	subq.l  #8,a0
	endif
	dbra    d3,.try
.ok:	rts
	endif
	move.b  #$55,d1
	bsr.s   .send
	move.b  #$aa,d1
.send:	move.b  d1,REG_SOUND
	move.w  #$4000,d2
.wait:	move.b  d0,REG_WATCHDOG
	cmp.b   REG_SOUND,d1                    ; the shim echoes each command
	dbeq    d2,.wait
	ifne DIAGBUILD
	move.w  d2,(a0)+
	clr.w   d0
	move.b  REG_SOUND,d0
	move.w  d0,(a0)+
	endif
	ifeq DIRECT-1
	cmp.b   REG_SOUND,d1                    ; (Z: echoed)
	endif
	rts

; ================================================================ video init
; blank fix layer, hide every sprite, every sprite tile blank (the BIOS leaves tile 0
; with attributes $ffff, i.e. tile $f0000: real tiles since the C ROM holds tiles
; above $10000), black backdrop
hal_video_init:
	ifne FZ_PD
	clr.w   G_SPRRAM+$1df0          ; (hal/fz.s FZ_HCOK: the HUD cache's shown bits never outlive
	endif                           ; a session: the sprite RAM persists on the MiSTer)
	lea     REG_VRAMADDR,a0
	move.w  #1,REG_VRAMMOD
	move.w  #0,(a0)                 ; SCB1: 448 sprites x 32 rows
	move.w  #$7000/2-1,d1
.scb1:	move.w  #BLANK_TILE,2(a0)
	move.w  #0,2(a0)
	move.b  d0,REG_WATCHDOG
	dbra    d1,.scb1
	move.w  #FIXMAP,(a0)
	move.w  #$500-1,d1
.fix:	move.w  #$0000,2(a0)
	move.b  d0,REG_WATCHDOG
	dbra    d1,.fix
	move.w  #SCB2,(a0)
	move.w  #$600-1,d1
.scb:	move.w  #$0000,2(a0)            ; SCB2 shrink 0 / SCB3 height 0 / SCB4 x 0
	dbra    d1,.scb
	move.w  #$0000,BACKDROP
	rts

; ================================================================ I/O mirror
; The original reads its VS9209 ports from a RAM mirror refreshed every frame.
hal_io_init:
	lea     IO_MIRROR,a0
	moveq   #$7f,d1
.clr:	move.b  #$ff,(a0)+
	dbra    d1,.clr
	move.b  #$00,IO_MIRROR+$2d      ; port G: sound latch not pending
	move.b  #$00,IO_MIRROR+$2f      ; port H: region jumper "Any"
	bsr     hal_dips
	bra     hal_inputs

; DSW1/DSW2 from the soft DIPs (the BIOS's chosen index per option, copied at the
; takeover; tools/aerofgt2neo.py SOFTDIPS): each chosen setting's bits ORed into the
; base.  An index out of range (no settings yet) gives the option's default.
hal_dips:
	movem.l d0-d5/a0-a1,-(sp)
	lea     hal_dipdata(pc),a0
	lea     HAL_SOFTDIP+6,a1
	moveq   #SOFTDIP_BASE1,d2
	move.w  #SOFTDIP_BASE2,d3
	moveq   #0,d1
	move.b  (a0)+,d1
	subq.w  #1,d1
.o:	moveq   #0,d4
	move.b  (a0)+,d4                ; choices
	moveq   #0,d5
	move.b  (a0)+,d5                ; default
	moveq   #0,d0
	move.b  (a1)+,d0                ; chosen
	cmp.w   d4,d0
	blo.s   .in
	move.w  d5,d0
.in:	add.w   d0,d0
	or.b    (a0,d0.w),d2
	or.b    1(a0,d0.w),d3
	add.w   d4,d4
	adda.w  d4,a0
	dbra    d1,.o
	move.b  d2,IO_MIRROR+$27        ; DSW1
	move.b  d3,IO_MIRROR+$29        ; DSW2
	movem.l (sp)+,d0-d5/a0-a1
	rts
	include "dips.inc"

; P1/P2/SYSTEM; clobbers d0
hal_inputs:
	move.b  REG_P1CNT,d0
	ori.b   #$c0,d0
	move.b  d0,IO_MIRROR+$21
	move.b  REG_P2CNT,d0
	ori.b   #$c0,d0
	move.b  d0,IO_MIRROR+$23
	; SYSTEM: b0 coin1 b1 coin2 b2 start1 b3 start2 b6 service, active low
	moveq   #-1,d0
	btst    #0,REG_STATUS_A
	bne.s   .c1
	bclr    #0,d0
.c1:	btst    #1,REG_STATUS_A
	bne.s   .c2
	bclr    #1,d0
.c2:	btst    #0,REG_STATUS_B
	bne.s   .s1
	bclr    #2,d0
.s1:	btst    #2,REG_STATUS_B
	bne.s   .s2
	bclr    #3,d0
.s2:	btst    #2,REG_STATUS_A
	bne.s   .sv
	bclr    #6,d0
.sv:	move.b  d0,IO_MIRROR+$25
	bclr    #0,IO_MIRROR+$2d        ; sound latch never pending at a frame boundary
	rts

