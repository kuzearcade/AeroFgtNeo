; Aero Fighters -> Neo Geo hardware abstraction layer (HAL)
;
; The original 68K program runs unmodified in place (operands relocated by
; tools/reloc.py, same size and cycle count).  The HAL owns the Neo hardware:
; boot takeover, the virtual vblank, inputs and video conversion.
;
; Interrupts
;   level 1 (Neo vblank) : BIOS before takeover; masked afterwards (original SR
;                          immediates are remapped IPL 0 -> 1 by tools/reloc.py)
;   level 2 (LSPC timer) : the virtual vblank (the original's IRQ1) plus the HAL's
;                          own probe/wake/sync events, told apart by HAL_MODE
;
; Exact timing
;   "virtual time" v = the original board's 68000 cycle count.  The Neo runs the
;   original code cycle for cycle, so during game execution
;       neo_cycles = v + O          (O = 0 mod 10 so the E clock phase of every
;                                    interrupt acknowledge matches the original)
;   Virtual vblank k is asserted by the LSPC timer at T_k = y_k + O, where y_k is
;   the first post-IACK-parity (odd) cycle >= floor(k * 1/61.31 s), minus 2.  The HAL then:
;     1. enters a NOP sled; a "probe" expiry at T_k + Q1 lands in it and the
;        stacked PC gives the exact cycle X at which the virtual IRQ was taken
;        (unique because X = 5 mod 10 after E clock synchronisation),
;     2. does its work (inputs, video) outside virtual time,
;     3. STOPs until a "wake" expiry W and resumes the original handler at
;        exactly tau_w + C2, giving the new offset O' = tau_w + C2 - e_k.
;   Timer chain per frame:  T_k --Q1--> probe --R_w--> W --R_next--> T_k+1
;   The reload register is always written one expiry ahead (LSPC semantics).

