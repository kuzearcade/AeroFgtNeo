MODE_DETECT     equ 11              ; boot: which timing model (hal_detect)

; MiSTer NeoGeo core (measured with the timing lab, hal/lab.s): its 68000 takes an
; interrupt LAT_M cycles after the boundary whatever the E clock (no VPA sync), a STOP
; wakes STOPW cycles after the expiry, and an expiry loaded relatively (TIMER_LOAD_REL)
; comes RELOFS cycles later than in MAME; reloads, the boundary rule (first boundary
; >= expiry + 6) and instruction timing are MAME's.  One sled position then leaves the
; entry time 2 cycles open: probe 1b, Q1B after probe 1 (Q1B - LAT_M - H1 = 2 mod 4),
; closes it.  hal_detect picks the model at boot (HAL_MISTER); its handlers are
; reached through the end of the mode chain (each check passed: 32 cycles).
LAT_M           equ 44
STOPW           equ 52
RELOFS          equ 12
H1              equ 312+160         ; probe-1 vector start -> first sled-1b NOP
Q1B             equ 602+160
SLED1B_NOPS     equ 128
PREFIX_PB       equ 376             ; probe-1b vector start -> vernier entry
; The wake is pinned the same way: probe 2, then probe 2b Q2B later (Q2B - LAT_M - H2
; = 2 mod 4); probe 2b's handler loads T_next and resumes the original handler on a
; fixed path (C_LB, C2PB from its vector start), so the load is one constant.
C_S2M           equ C_S2+40+160     ; wake vector start -> first sled NOP (+ the Q2B reload)
H2              equ 204+256         ; probe-2 vector start -> first sled-2b NOP
Q2B             equ 402+256
M2              equ (Q2B-LAT_M-H2-2)/4  ; probe 2b at m2+1 (probe-2 boundary W+Q2+6) or m2 (+8)
J2M             equ (Q2+6-STOPW-C_S2M+3)/4      ; probe 2's sled position (about)
SLED2B_NOPS     equ 96
C_LB            equ 338             ; probe-2b vector start -> TIMERLOW write instruction
C2PB            equ 644             ; probe-2b vector start -> the original handler
P2B_OFFM        equ ((hal_sled2b+2*M2-hal_sled-2*JMIN)&$7e)/2
P2B_CLS_M       equ P2B_OFFM-(P2B_OFFM/5)*5     ; tracking class of probe 2b at m2

HAL_DIAG        equ 0               ; 1: per-slot timestamps and deadline-check traces
COMMIT_LINES    equ 16              ; slot lines the real-vblank work needs (before the margin)

