"""Patch the original Aero Fighters Z80 sound program for the Neo Geo.

Every patch keeps the instruction length.  Port and RAM differences:
  YM2610           ports 0-3          -> 4-7   (immediate ports patched; OUT (C),r -> RST)
  sound latch      IN A,($0C)         -> IN A,($00)
  bank select      OUT ($04),A        -> RST 28h (Neo 4-window banking, see z80/shim.s)
  RAM              0x7800-0x7fff      -> 0xf800-0xffff  (SP top 0x8000 -> 0x0000)
  ADPCM-B          sample addresses   +0x100000 (shared V ROM, RST 30h)
  reset / NMI      0x0000, 0x0066     -> shim (MVS BIOS handshake, then the original)

The original power-on sequence (after its stack setup, up to its jump into the main
loop) is copied out of the user's ROM at build time into build/z80reset.inc, which
z80/shim.s includes: the repository holds none of the original program.
"""

import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import z80  # noqa: E402

VASMZ80 = os.path.join(ROOT, "third_party", "vasm", "vasmz80_oldstyle")
RST_FOR_OUTC = {0x79: 0xcf, 0x59: 0xd7, 0x61: 0xdf, 0x69: 0xe7}   # OUT (C),A/E/H/L
RST_BANK = 0xef
RST_ADPCMB_HI = 0xf7
# ld a,(hl) feeding YM registers 0x13 / 0x15 (ADPCM-B start/end high bytes)
ADPCMB_HI_LOADS = (0x1874, 0x18a0)


def load_seeds():
    with open(os.path.join(ROOT, "analysis", "z80_seeds.txt")) as f:
        return sorted(int(l, 16) for l in f if l.strip() and not l.startswith("#"))


def reset_include(mem, build_dir):
    """build/z80reset.inc: the original power-on sequence, from the instruction after its
    LD SP to its first unconditional JP (inclusive), as bytes. RAM operands move to
    0xf800 as everywhere else; jumps inside the block become labels (the block runs at
    the shim's address); calls and jumps out of it keep their ROM addresses."""
    a = 0
    while True:
        i = z80.decode(mem, a)
        a += i.length
        if mem[i.addr] == 0x31:              # LD SP,nn: the shim sets the stack itself
            break
        if a > 0x20:
            raise SystemExit("z80 reset: no LD SP in the first 32 bytes")
    start, ins = a, []
    while True:
        i = z80.decode(mem, a)
        ins.append(i)
        a += i.length
        if i.flow == "jump":
            break
        if a - start > 0x40 or i.flow in ("ret", "ijump"):
            raise SystemExit("z80 reset: no closing JP after %04x" % start)
    end = a
    lines = ["; generated by tools/z80patch.py from the sound ROM %04x-%04x: do not edit" % (start, end - 1)]
    for i in ins:
        raw = mem[i.addr:i.addr + i.length]
        lab = "rs_%04x:" % i.addr
        if i.imm16_off is None:
            if raw[0] in z80.JR:
                t = (i.addr + 2 + (raw[1] - 256 if raw[1] > 127 else raw[1])) & 0xffff
                if not start <= t < end:
                    raise SystemExit("z80 reset: relative jump out of the block at %04x" % i.addr)
            body = "db " + ",".join("$%02x" % b for b in raw)
        else:
            v = i.imm16
            if i.flow is None and 0x7800 <= v <= 0x7fff:
                v = "$%04x" % ((v + 0x8000) & 0xffff)
            elif i.targets and start <= v < end:
                v = "rs_%04x" % v
            else:
                v = "$%04x" % v
            pre = raw[:i.imm16_off]
            post = raw[i.imm16_off + 2:]
            body = "db " + ",".join("$%02x" % b for b in pre) + "\n\tdw " + v
            if post:
                body += "\n\tdb " + ",".join("$%02x" % b for b in post)
        lines.append(lab + "\t" + body)
    with open(os.path.join(build_dir, "z80reset.inc"), "w") as f:
        f.write("\n".join(lines) + "\n")


def assemble(src, build_dir, name):
    out = os.path.join(build_dir, name)
    r = subprocess.run([VASMZ80, "-quiet", "-Fbin", "-I", build_dir, "-o", out, src],
                       capture_output=True, text=True)
    if r.returncode:
        raise SystemExit(r.stdout + r.stderr)
    return open(out, "rb").read()


def patch(rom, build_dir, log):
    m = bytearray(rom)
    mem = bytes(rom[:0x8000]) + b"\0" * 4
    seeds = load_seeds()
    count = {}
    soft_restarts = []   # the driver restarts itself with jp $0000; 0x0000 is now the shim
    seedset = set(seeds)
    targets = set()
    for a in seeds:
        targets.update(z80.decode(mem, a).targets)

    def note(k):
        count[k] = count.get(k, 0) + 1

    for a in seeds:
        i = z80.decode(mem, a)
        if i.kind == "io_c":
            op2 = mem[a + 1]
            if op2 not in RST_FOR_OUTC:
                raise SystemExit("unhandled (C) I/O %02x at %04x" % (op2, a))
            if mem[a - 1] == 0xfb and (a - 1) in seedset:
                # 'ei ; out (c),r' is atomic on the Z80 (EI waits one instruction).  The
                # RST would open an interrupt window before the write, so emit
                # 'rst ; nop ; ei' instead: the write stays under DI and interrupts
                # come back one instruction later than on the original.
                if a in targets:
                    raise SystemExit("jump target on 'out (c)' after EI at %04x" % a)
                m[a - 1], m[a], m[a + 1] = RST_FOR_OUTC[op2], 0x00, 0xfb
                note("ei; out(c) -> rst; nop; ei")
            else:
                m[a], m[a + 1] = RST_FOR_OUTC[op2], 0x00
                note("out(c)")
        elif i.kind == "io_block":
            raise SystemExit("block I/O at %04x not supported" % a)
        elif i.kind == "out":
            if i.port <= 3:
                m[a + 1] = i.port + 4
                note("out ym")
            elif i.port == 4:
                m[a], m[a + 1] = RST_BANK, 0x00
                note("bank")
            elif i.port == 8:
                note("ack (Neo: NMI enable, harmless)")
            else:
                raise SystemExit("unexpected OUT ($%02x) at %04x" % (i.port, a))
        elif i.kind == "in":
            if i.port in (0, 2):
                m[a + 1] = i.port + 4
                note("in ym")
            elif i.port == 0x0c:
                m[a + 1] = 0x00
                note("latch")
            else:
                raise SystemExit("unexpected IN ($%02x) at %04x" % (i.port, a))
        if i.flow in ("jump", "call", "branch") and i.imm16 == 0x0000:
            soft_restarts.append(a)
        # RAM is 0x7800-0x7fff; 0x8000 is only the stack top for LD SP (elsewhere it is
        # the start of the banked ROM window)
        is_ram = 0x7800 <= i.imm16 <= 0x7fff if i.imm16 is not None else False
        is_sp_top = i.imm16 == 0x8000 and mem[a] == 0x31
        if i.imm16_off is not None and (is_ram or is_sp_top) and i.flow is None:
            v = (i.imm16 + 0x8000) & 0xffff
            m[a + i.imm16_off] = v & 0xff
            m[a + i.imm16_off + 1] = v >> 8
            note("ram")
    for a in ADPCMB_HI_LOADS:
        assert m[a] == 0x7e and m[a + 1] == 0xfb, "ADPCM-B load site moved at %04x" % a
        m[a] = RST_ADPCMB_HI
        note("adpcm-b")
    # shim + RST handlers (the original reset code runs from the shim: build/z80reset.inc)
    reset_include(mem, build_dir)
    rst = assemble(os.path.join(ROOT, "z80", "rst.s"), build_dir, "z80rst.bin")
    shim = assemble(os.path.join(ROOT, "z80", "shim.s"), build_dir, "z80shim.bin")
    assert len(rst) <= 0x30 and len(shim) <= 0x800
    m[0x0008:0x0008 + len(rst)] = rst
    m[0x7800:0x7800 + len(shim)] = shim
    lst = shim_symbols(build_dir)
    m[0x0000:0x0003] = bytes([0xc3, lst["shim_reset"] & 0xff, lst["shim_reset"] >> 8])
    assert mem[0x66:0x69] == b"\xf5\xc5\xe5", "NMI entry changed"
    m[0x0066:0x0069] = bytes([0xc3, lst["shim_nmi"] & 0xff, lst["shim_nmi"] >> 8])
    for a in soft_restarts:
        m[a + 1] = lst["game_reset"] & 0xff
        m[a + 2] = lst["game_reset"] >> 8
        note("soft restart -> game_reset")
    for k, v in sorted(count.items()):
        log.write("z80 patch %-36s %d\n" % (k, v))
    return m


def shim_symbols(build_dir):
    out = os.path.join(build_dir, "z80shim.lst")
    r = subprocess.run([VASMZ80, "-quiet", "-Fbin", "-I", build_dir, "-L", out, "-o", os.devnull,
                        os.path.join(ROOT, "z80", "shim.s")], capture_output=True, text=True)
    if r.returncode:
        raise SystemExit(r.stdout + r.stderr)
    syms = {}
    for line in open(out):
        p = line.split()
        if len(p) >= 2 and p[1].startswith("A:"):
            syms[p[0]] = int(p[1][2:], 16)
    return syms
